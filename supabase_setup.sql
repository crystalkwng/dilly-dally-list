-- The Dilly Dally List: database setup
-- Run this in Supabase Dashboard -> SQL Editor -> New query -> Run.

create table if not exists public.adventures (
    id bigint generated by default as identity primary key,
    name text not null,
    category text not null default 'Hiking',
    location text not null default '',
    distance_km double precision,
    difficulty text not null default 'Unknown',
    status text not null default 'Want to go',
    notes text not null default '',
    map_url text not null default '',
    latitude double precision,
    longitude double precision,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- The app connects from its Python server using the Supabase service-role key.
-- Keep that key ONLY in Streamlit Secrets. Never put it in app.py or GitHub.
-- Enable RLS and remove direct access from public API roles as a safety default.
alter table public.adventures enable row level security;
revoke all on table public.adventures from anon, authenticated;
